import assert from "node:assert/strict";
import sharp from "sharp";

export async function verifyCatalogMediaUi({page,publicPage,expect,admin,rpc,runId,catalogIds}) {
  await publicPage.emulateMedia({reducedMotion:"reduce"});
  const created=await rpc(admin,"save_catalog_item",{p_item:{name:`Gallery fixture ${runId}`,description:"Synthetic keyboard angles and sound test",category:"keyboard",type:"product",unit:"bộ",price:120000,cost:60000,active:true,lubePackage:"",imagePath:null}});
  assert.equal(created.data?.ok,true);const id=created.data.id;catalogIds.push(id);
  await page.goto(`http://localhost:3000/admin/catalog/${id}`);
  const editor=page.getByRole("region",{name:"Ảnh và sound test sản phẩm"});
  const images=await Promise.all(["#e8bc49","#c7d2dd","#4e6479"].map(async(color,index)=>({name:`fixture-angle-${index}.png`,mimeType:"image/png",buffer:await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600"><rect width="800" height="600" fill="#f4f4f4"/><rect x="65" y="180" width="670" height="240" rx="18" fill="${color}"/>${Array.from({length:40},(_,n)=>`<rect x="${90+(n%10)*62}" y="${205+Math.floor(n/10)*48}" width="50" height="36" rx="3" fill="white"/>`).join("")}<text x="400" y="500" text-anchor="middle" font-size="30">TEST FIXTURE · ANGLE ${index+1}</text></svg>`)).png().toBuffer()})));
  await editor.getByLabel(/Thêm ảnh ở các góc/).setInputFiles(images);
  await expect(editor.locator("li")).toHaveCount(3);
  await expect(editor.getByRole("status")).toContainText("Đã lưu 3 ảnh");
  const original=(await admin.client.from("products_services").select("image_paths,version,price_vnd,stock_quantity").eq("id",id).single()).data;
  assert.equal(original.image_paths.length,3);
  await editor.getByRole("button",{name:"Đặt ảnh 3 làm ảnh bìa",exact:true}).click();
  await expect(editor.getByRole("status")).toContainText("Đã lưu ảnh và sound test");
  await expect.poll(async()=> (await admin.client.from("products_services").select("image_path").eq("id",id).single()).data.image_path).toBe(original.image_paths[2]);
  await editor.getByLabel("Link YouTube hoặc TikTok",{exact:true}).fill("https://evil.example/video");
  await editor.getByRole("button",{name:"Lưu link sound test",exact:true}).click();
  await expect(editor.getByRole("status")).toContainText("Dùng link HTTPS");
  await editor.getByLabel("Tải video MP4",{exact:true}).setInputFiles({name:"fake.mp4",mimeType:"video/mp4",buffer:Buffer.from("renamed text is not a video")});
  await expect(editor.getByRole("status")).toContainText("File không phải MP4");
  // Generate an actual short H.264/AAC MP4 with an audio track; no external assets/providers.
  const recording=await publicPage.evaluate(async()=> {
    const mimeType=['video/mp4;codecs="avc1.42001E,mp4a.40.2"','video/mp4'].find(type=>MediaRecorder.isTypeSupported(type));
    if(!mimeType)throw new Error("Chromium cannot record an MP4 fixture");
    const canvas=document.createElement("canvas");canvas.width=320;canvas.height=180;
    const ctx=canvas.getContext("2d"),audio=new AudioContext(),destination=audio.createMediaStreamDestination(),oscillator=audio.createOscillator();
    oscillator.frequency.value=220;oscillator.connect(destination);await audio.resume();oscillator.start();
    const stream=canvas.captureStream(10);for(const track of destination.stream.getAudioTracks())stream.addTrack(track);
    const recorder=new MediaRecorder(stream,{mimeType}),parts=[];
    recorder.ondataavailable=e=>parts.push(e.data);
    const done=new Promise(resolve=>recorder.onstop=resolve);recorder.start();
    for(let n=0;n<15;n++){ctx.fillStyle=n%2?"#f0bf50":"#35465c";ctx.fillRect(0,0,320,180);ctx.fillStyle="white";ctx.font="20px Arial";ctx.fillText("TEST SOUND FIXTURE",40,95);await new Promise(resolve=>setTimeout(resolve,100));}
    recorder.stop();await done;oscillator.stop();stream.getTracks().forEach(track=>track.stop());await audio.close();
    return Array.from(new Uint8Array(await new Blob(parts,{type:"video/mp4"}).arrayBuffer()));
  });
  await editor.getByLabel("Tải video MP4",{exact:true}).setInputFiles({name:"test-sound.mp4",mimeType:"video/mp4",buffer:Buffer.from(recording)});
  await expect(editor.getByRole("status")).toContainText("Đã lưu 1 video sound test");
  await page.setViewportSize({width:1440,height:1000});await editor.scrollIntoViewIfNeeded();
  await page.screenshot({caret:"initial",path:"output/playwright/catalog-gallery-admin-desktop.png",fullPage:true});
  await page.setViewportSize({width:375,height:812});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({caret:"initial",path:"output/playwright/catalog-gallery-admin-mobile.png",fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await publicPage.setViewportSize({width:1440,height:1000});
  await publicPage.goto(`http://localhost:3000/shop/${id}`);
  const gallery=publicPage.getByRole("region",{name:"Thư viện ảnh và sound test"}), stage=gallery.getByRole("region",{name:"Ảnh và video sản phẩm"});
  await expect(gallery.getByRole("status"),"initial gallery").toHaveText("Ảnh 1 / 4");
  await expect(gallery.locator(".product-gallery-slide img").first()).toHaveAttribute("src",new RegExp(original.image_paths[2]));
  await stage.focus();await publicPage.keyboard.press("ArrowRight");await expect(gallery.getByRole("status")).toHaveText("Ảnh 2 / 4");
  await publicPage.screenshot({caret:"initial",path:"output/playwright/catalog-gallery-buyer-desktop.png",fullPage:true});
  await gallery.getByRole("button",{name:"Xem video sound test",exact:true}).click();
  const video=gallery.locator("video");await expect(video).toBeVisible();
  assert.equal(await video.evaluate(el=>el.paused),true,"no autoplay");
  await video.evaluate(el=>el.play());
  await expect.poll(()=>video.evaluate(el=>el.readyState>=2 && el.videoWidth>0 && !el.paused)).toBe(true);
  assert.equal(await video.evaluate(el=>el.audioTracks ? el.audioTracks.length>0 : el.webkitAudioDecodedByteCount>0),true,"audio decodes");
  await gallery.getByRole("button",{name:"Xem ảnh 1",exact:true}).click();
  await expect(video).toHaveCount(0,"changing slide unmounts and stops the sound test");
  await expect(gallery.getByRole("status"),"back from video").toHaveText("Ảnh 1 / 4");
  await publicPage.setViewportSize({width:375,height:812});
  await expect.poll(()=>publicPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await stage.scrollIntoViewIfNeeded();
  const touch=await publicPage.context().newCDPSession(publicPage);
  await touch.send("Emulation.setTouchEmulationEnabled",{enabled:true});
  const rect=await stage.boundingBox(),y=rect.y+rect.height/2;
  await touch.send("Input.dispatchTouchEvent",{type:"touchStart",touchPoints:[{x:rect.x+rect.width*.85,y}]});
  for(let n=1;n<=8;n++) await touch.send("Input.dispatchTouchEvent",{type:"touchMove",touchPoints:[{x:rect.x+rect.width*(.85-.7*n/8),y}]});
  await touch.send("Input.dispatchTouchEvent",{type:"touchEnd",touchPoints:[]});
  await expect(gallery.getByRole("status")).toHaveText("Ảnh 2 / 4");
  await touch.send("Emulation.setTouchEmulationEnabled",{enabled:false});
  await touch.detach();
  await stage.focus();await publicPage.keyboard.press("Home");
  await expect(gallery.getByRole("status"),"Home after swipe").toHaveText("Ảnh 1 / 4");
  await publicPage.keyboard.press("ArrowRight");await expect(gallery.getByRole("status")).toHaveText("Ảnh 2 / 4");
  await expect(gallery.locator(".product-gallery-slide img")).toHaveAttribute("src",new RegExp(original.image_paths[0]));
  await publicPage.screenshot({caret:"initial",path:"output/playwright/catalog-gallery-buyer-mobile.png",fullPage:true});
  await expect(gallery.getByRole("status")).toHaveText("Ảnh 2 / 4");
  await publicPage.setViewportSize({width:1440,height:1000});
  await expect(gallery.getByRole("status")).toHaveText("Ảnh 2 / 4");
  await expect(gallery.locator(".product-gallery-slide img")).toHaveAttribute("src",new RegExp(original.image_paths[0]));
  await publicPage.setViewportSize({width:375,height:812});
  // Remove a non-cover angle, then replace the uploaded video with a hosted sound test.
  await editor.getByRole("button",{name:"Gỡ ảnh 2",exact:true}).click();
  await expect(editor.locator("li")).toHaveCount(2);
  await editor.getByLabel("Link YouTube hoặc TikTok",{exact:true}).fill("https://www.tiktok.com/@fixture/video/123456789");
  await editor.getByRole("button",{name:"Lưu link sound test",exact:true}).click();
  await expect(editor.getByRole("status")).toContainText("Đã lưu ảnh và sound test");
  await publicPage.reload();await gallery.getByRole("button",{name:"Xem video sound test",exact:true}).click();
  await expect(gallery.getByRole("link",{name:"Xem sound test"})).toHaveAttribute("href","https://www.tiktok.com/@fixture/video/123456789");
  const current=(await admin.client.from("products_services").select("image_paths,video_path,video_url,price_vnd,stock_quantity").eq("id",id).single()).data;
  assert.equal(current.video_path,null);assert.equal(current.image_paths.length,2);
  assert.equal(current.price_vnd,original.price_vnd);assert.equal(current.stock_quantity,original.stock_quantity);
  await publicPage.close();
}
